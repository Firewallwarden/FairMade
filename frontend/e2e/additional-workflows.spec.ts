test('administrator stale decisions reload the final backend outcome instead of overwriting it', async ({ page }) => {
  const guest = await request.newContext({ baseURL: `http://127.0.0.1:${process.env.E2E_API_PORT}/api/v1/` })
  const credentials = { email: `browser-stale-${crypto.randomUUID().slice(0, 8)}@example.com`, password: process.env.E2E_PASSWORD }
  expect((await guest.post('auth/register', { data: credentials })).ok()).toBeTruthy()
  const token = await (await guest.post('auth/login', { data: credentials })).json()
  const application = await (await guest.post('seller-applications', { data: {}, headers: { Authorization: `Bearer ${token.access_token}` } })).json()
  const api = await signIn(page, 'admin')
  await page.goto(`/#/admin-applications/${application.id}`)
  await field(page, 'application-outcome', 'approved')
  await field(page, 'application-reason', 'Synthetic stale UI attempt')
  expect((await api.post(`admin/seller-applications/${application.id}/decision`, { data: { expected_revision: application.revision, outcome: 'denied', reason: 'Synthetic concurrent final decision' } })).ok()).toBeTruthy()
  page.once('dialog', dialog => dialog.accept())
  await page.getByRole('button', { name: 'Record final application decision' }).click()
  await expect(page.getByText(/Final decision: denied/)).toBeVisible()
  await expect(page.getByText(/current state has been reloaded/)).toBeVisible()
  await expect(page.getByRole('button', { name: 'Record final application decision' })).toHaveCount(0)
  await guest.dispose(); await api.dispose()
})
