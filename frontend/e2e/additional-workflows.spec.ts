import { test, expect, request } from './fixtures'
import { signIn, apiForRole, seedListing, field, posted, createProduct, openProduct, chooseHistory } from './helpers'

test('photo upload, authenticated image viewing and deletion use the real media endpoints', async ({ page }) => {
  const api = await signIn(page)
  const product = await createProduct(api)
  await openProduct(page, product.id, 'Photos & description')
  const dataUrl = await page.evaluate(() => {
    const canvas = document.createElement('canvas'); canvas.width = 16; canvas.height = 16
    canvas.getContext('2d')!.fillRect(0, 0, 16, 16)
    return canvas.toDataURL('image/png')
  })
  await page.locator('[name="product-photo"]').setInputFiles({ name: 'synthetic-product.png', mimeType: 'image/png', buffer: Buffer.from(dataUrl.split(',')[1], 'base64') })
  const photo = await posted(page, '/photos', () => page.getByRole('button', { name: 'Upload private photo' }).click())
  await expect(page.getByRole('img', { name: 'Private product photo 1' })).toBeVisible()
  const removal = page.waitForResponse(r => r.url().endsWith(`/photos/${photo.id}`) && r.request().method() === 'DELETE')
  await page.getByRole('button', { name: /Delete unused photo|Remove photo/ }).click()
  expect((await removal).status()).toBe(204)
  await expect(page.getByRole('img', { name: 'Private product photo 1' })).toHaveCount(0)
  await api.dispose()
})

test('seller business reports invoke insights, forecasts, calendar, advice and sales APIs', async ({ page }) => {
  const api = await signIn(page)
  const { product, review, analysis } = await seedListing(api)
  await openProduct(page, product.id, 'Business reports')
  await page.getByText('Choose a private cost basis for future order snapshots', { exact: true }).click()
  await chooseHistory(page, 'Future-order cost basis', analysis.id)
  await posted(page, '/sales-cost-basis', () => page.getByRole('button', { name: 'Save future-order cost basis' }).click())
  for (const mode of ['insights', 'forecast', 'calendar', 'advice', 'sales']) {
    await page.locator('select:has(option[value="insights"])').selectOption(mode)
    if (mode === 'advice') await chooseHistory(page, 'Saved pricing review', review.id)
    const response = page.waitForResponse(r => r.url().includes('/api/v1/') && !r.url().includes('limit=') && r.request().resourceType() === 'fetch')
    await page.getByRole('button', { name: 'Build backend report' }).click()
    expect((await response).ok()).toBeTruthy()
    await expect(page.getByRole('alert')).toHaveCount(0)
  }
  await api.dispose()
})

test('buyer saves/removes favorites and compares two current public Passports', async ({ page }) => {
  const sellerApi = await apiForRole('seller')
  const first = await seedListing(sellerApi), second = await seedListing(sellerApi)
  const api = await signIn(page, 'buyer')
  await page.goto(`/#/market/${first.listing.id}`)
  await posted(page, '/favorites', () => page.getByRole('button', { name: 'Save this product' }).click())
  await page.goto('/#/favorites')
  await expect(page.getByRole('heading', { name: first.product.name, exact: true })).toBeVisible()
  const remove = page.waitForResponse(r => r.request().method() === 'DELETE' && r.url().includes('/favorites/'))
  await page.getByRole('button', { name: 'Remove bookmark' }).first().click()
  expect((await remove).ok()).toBeTruthy()
  await page.goto(`/#/compare/${first.listing.id},${second.listing.id}`)
  await expect(page.getByRole('region', { name: 'Product comparison table' })).toBeVisible()
  await expect(page.getByRole('table')).toContainText(first.product.name)
  await expect(page.getByRole('table')).toContainText(second.product.name)
  await api.dispose(); await sellerApi.dispose()
})

