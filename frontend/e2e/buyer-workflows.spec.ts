import { test, expect } from './fixtures'
import { signIn, apiForRole, seedListing, field, posted } from './helpers'

test('buyer previews and reserves stock, both participants message, seller cancels and stock refreshes', async ({ page, browser }) => {
  const sellerApi = await apiForRole('seller')
  const { product, listing } = await seedListing(sellerApi)
  const buyerApi = await signIn(page, 'buyer')
  await page.goto(`/#/market/${listing.id}`)
  await field(page, 'purchase-quantity', '2')
  await posted(page, '/orders/preview', () => page.getByRole('button', { name: 'Review purchase subtotal' }).click())
  const order = await posted(page, '/orders', () => page.getByRole('button', { name: 'Reserve stock & continue' }).click())
  await expect(page.getByText('Backend order status:', { exact: false })).toBeVisible()
  await field(page, 'order-message', 'Synthetic buyer pickup question <script>plain text</script>')
  await posted(page, '/messages', () => page.getByRole('button', { name: 'Send private message' }).click())
  const sellerContext = await browser.newContext({ baseURL: new URL(page.url()).origin })
  const sellerPage = await sellerContext.newPage()
  const sellerSession = await signIn(sellerPage, 'seller')
  await sellerPage.goto(`/#/seller-orders/${order.id}`)
  await expect(sellerPage.getByText('Synthetic buyer pickup question <script>plain text</script>', { exact: true })).toBeVisible()
  await field(sellerPage, 'order-message', 'Synthetic seller reply')
  await posted(sellerPage, '/messages', () => sellerPage.getByRole('button', { name: 'Send private message' }).click())
  await page.getByRole('button', { name: 'Refresh order conversation' }).click()
  await expect(page.getByText('Synthetic seller reply', { exact: true })).toBeVisible()
  await expect(sellerPage.getByText('No pickup updates on this page.')).toBeVisible()
  sellerPage.once('dialog', dialog => dialog.accept())
  await posted(sellerPage, '/cancel', () => sellerPage.getByRole('button', { name: 'Cancel unpaid order as seller' }).click())
  await expect(sellerPage.getByRole('heading', { name: 'Availability after cancellation' })).toBeVisible()
  await expect(sellerPage.getByText(/50 selling units/)).toBeVisible()
  const inventory = await (await sellerApi.get(`products/${product.id}/inventory`)).json()
  expect(inventory.available).toBe(50)
  await page.getByRole('button', { name: 'Refresh saved status', exact: true }).click()
  await expect(page.getByText('cancelled', { exact: true })).toBeVisible()
  await sellerSession.dispose(); await sellerApi.dispose(); await buyerApi.dispose(); await sellerContext.close()
})

