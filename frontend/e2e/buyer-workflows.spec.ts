test('marketplace radius discovery returns backend distances and keeps supported ordering', async ({ page }) => {
  const sellerApi = await apiForRole('seller')
  const { product } = await seedListing(sellerApi)
  const fronts = await (await sellerApi.get('seller/storefronts')).json()
  let front = fronts.items[0]
  const content = { display_name: 'Synthetic browser maker', description: 'Synthetic test storefront', location: 'Synthetic town', approximate_area: { label: 'Synthetic town center', latitude: '40.00', longitude: '-89.00', basis: 'seller_chosen_approximate' } }
  front = await (await sellerApi[front ? 'put' : 'post'](`seller/storefronts${front ? `/${front.id}` : ''}`, { data: { ...content, ...(front ? { expected_revision: front.revision } : {}) } })).json()
  const preview = await (await sellerApi.get(`seller/storefronts/${front.id}/preview`)).json()
  expect((await sellerApi.post(`seller/storefronts/${front.id}/publish`, { data: { expected_revision: preview.revision, preview_hash: preview.preview_hash, approved: true } })).ok()).toBeTruthy()
  await page.goto('/#/market')
  await page.getByLabel('Search products within a radius').check()
  await field(page, 'market-query', product.name)
  await field(page, 'origin-latitude', '40.00')
  await field(page, 'origin-longitude', '-89.00')
  await field(page, 'origin-radius', '25')
  await field(page, 'market-sort', 'price_asc')
  const response = await posted(page, '/discovery/listings', () => page.getByRole('button', { name: 'Find your kind of good' }).click())
  expect(response.items.length).toBeGreaterThan(0)
  await expect(page.getByText(/Estimated distance:/)).toBeVisible()
  await expect(page.getByLabel('Location label', { exact: true })).toBeDisabled()
  expect(page.url()).not.toContain('40.00')
  await page.goto('/#/storefronts')
  await page.getByText('Nearby search (optional)', { exact: true }).click()
  await field(page, 'maker-latitude', '40.00')
  await field(page, 'maker-longitude', '-89.00')
  await field(page, 'maker-radius', '25')
  await posted(page, '/discovery/storefronts', () => page.getByRole('button', { name: 'Find makers', exact: true }).click())
  await expect(page.getByRole('link', { name: 'Meet this maker' }).first()).toBeVisible()
  await sellerApi.dispose()
})

test('buyer preferences require consent, request suggestions and can be disabled', async ({ page }) => {
  const api = await signIn(page, 'buyer')
  await page.goto('/#/preferences')
  await field(page, 'preference-budget', '20')
  await page.locator('[name="preference-type"][value="sourdough"]').check()
  await expect(page.getByRole('button', { name: 'Save reviewed preferences' })).toBeDisabled()
  await page.locator('[name="confirm-preferences"]').check()
  await posted(page, '/personalization', () => page.getByRole('button', { name: 'Save reviewed preferences' }).click())
  await posted(page, '/suggestions', () => page.getByRole('button', { name: 'Find matches with my saved choices' }).click())
  await page.getByRole('button', { name: 'Disable personalization & clear preferences' }).click()
  await expect(page.getByRole('button', { name: 'Find matches with my saved choices' })).toHaveCount(0)
  const profile = await (await api.get('buyer/personalization')).json()
  expect(profile.enabled).toBe(false)
  await api.dispose()
})

test('signed-out and buyer-only routes protect private workspaces and remain keyboard navigable', async ({ page }) => {
  for (const route of ['seller', 'materials', 'livestock/groups', 'receipts', 'admin-applications']) {
    await page.goto(`/#/${route}`)
    await expect(page.getByRole('link', { name: 'Sign in or create an account' })).toBeVisible()
  }
  const api = await signIn(page, 'buyer')
  await page.goto('/#/admin-applications')
  await expect(page.getByText('Administrator access is required.')).toBeVisible()
  await page.goto('/#/seller')
  await expect(page.getByRole('link', { name: 'View seller application' })).toBeVisible()
  await page.goto('/#/market')
  await page.keyboard.press('Tab')
  expect(await page.evaluate(() => document.activeElement !== document.body)).toBeTruthy()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1)).toBeTruthy()
  await api.dispose()
})
