const today = () => new Date().toISOString().slice(0, 10)

test('seller creates and edits a product, calculates economics, and reopens the saved analysis', async ({ page }) => {
  const api = await signIn(page)
  await page.goto('/#/seller')
  await field(page, 'product-name', `Browser loaf ${crypto.randomUUID().slice(0, 8)}`)
  await field(page, 'product-type', 'sourdough')
  await field(page, 'product-unit', 'loaf')
  const product = await posted(page, '/products', () => page.getByRole('button', { name: /Create private product/ }).click())
  await expect(page.getByRole('heading', { name: 'Your saved cost picture' })).toBeVisible()
  await page.getByText('Edit private product', { exact: false }).click()
  await field(page, 'edit-name', 'Updated synthetic browser loaf')
  await posted(page, `/products/${product.id}`, () => page.getByRole('button', { name: 'Save private details', exact: true }).click())
  await page.locator('[name^="cost-label-"]').fill('Synthetic flour')
  await page.locator('[name^="cost-amount-"]').fill('10.00')
  await field(page, 'yield', '10')
  for (const [name, value] of Object.entries({ 'margin-minimum': '20', 'margin-maximum': '30', 'fee-rate': '3', 'fee-fixed': '0.30', 'units-per-order': '1', 'proposed-price': '4' })) await field(page, name, value)
  await posted(page, '/analyses', () => page.getByRole('button', { name: 'Calculate & save private analysis' }).click())
  await expect(page.getByText('Production cost per unit', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: /Quality Lock/ }).first().click()
  await page.getByRole('button', { name: /Calculate/ }).first().click()
  await chooseHistory(page, 'Saved analyses')
  await expect(page.getByText('Production cost per unit', { exact: true })).toBeVisible()
  await api.dispose()
})

