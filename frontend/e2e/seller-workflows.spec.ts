test('older analysis selections remain pinned across navigable history pages', async ({ page }) => {
  const api = await signIn(page)
  const product = await createProduct(api)
  for (let index = 0; index < 21; index++) await seedAnalysis(api, product.id)
  await openProduct(page, product.id)
  const selected = await chooseHistory(page, 'Saved analyses')
  const picker = page.getByRole('group', { name: 'Saved analyses', exact: true })
  await picker.getByRole('button', { name: 'Next saved analyses', exact: true }).click()
  await expect(picker.getByText('Page 2', { exact: true })).toBeVisible()
  await expect(picker.locator('select')).toHaveValue(selected)
  await expect(picker.locator(`option[value="${selected}"]`)).toContainText('selected from another page')
  await picker.getByRole('button', { name: 'Previous saved analyses', exact: true }).click()
  await expect(picker.locator('select')).toHaveValue(selected)
  await api.dispose()
})

test('material receipt, usage, metadata and balance/history are saved on the backend', async ({ page }) => {
  const materialName = `Edited synthetic flour ledger ${crypto.randomUUID().slice(0, 8)}`
  const api = await signIn(page)
  await page.goto('/#/materials')
  await field(page, 'material-name', 'Synthetic flour ledger')
  const material = await posted(page, '/seller/materials', () => page.getByRole('button', { name: /Create private material/ }).click())
  await expect(page.getByRole('heading', { name: 'Record a quantity change.' })).toBeVisible()
  await field(page, 'movement-quantity', '1000')
  await field(page, 'movement-date', today())
  await field(page, 'movement-reason', 'Synthetic received flour')
  await posted(page, '/movements', () => page.getByRole('button', { name: 'Record material movement', exact: true }).click())
  await page.getByLabel(/Movement type/).selectOption('usage')
  await field(page, 'movement-date', today())
  await field(page, 'movement-quantity', '100')
  await field(page, 'movement-reason', 'Synthetic batch usage')
  await posted(page, '/movements', () => page.getByRole('button', { name: 'Record material movement', exact: true }).click())
  await page.getByText('Edit material name/notes', { exact: true }).click()
  await field(page, 'material-edit-name', materialName)
  await posted(page, `/materials/${material.id}`, () => page.getByRole('button', { name: 'Save material metadata' }).click())
  await page.goto('/#/seller')
  await page.goto(`/#/materials/${material.id}`)
  await page.getByText('Edit material name/notes', { exact: true }).click()
  await expect(page.locator('[name="material-edit-name"]')).toHaveValue(materialName)
  await page.locator('summary').filter({ hasText: /^usage/ }).click()
  await expect(page.getByText(/Synthetic batch usage/)).toBeVisible()
  const saved = await (await api.get(`seller/materials/${material.id}`)).json()
  expect(Number(saved.on_hand)).toBe(900)
  await api.dispose()
})

