import { test, expect } from './fixtures'
import { signIn, apiForRole, seedListing, field, posted, openProduct } from './helpers'

test('buyer basket optimization, purchase preview and buyer/seller pair suggestions use approved storefront data', async ({ page, browser }) => {
  const sellerApi = await apiForRole('seller')
  const first = await seedListing(sellerApi), second = await seedListing(sellerApi)
  const fronts = await (await sellerApi.get('seller/storefronts')).json()
  let front = fronts.items[0]
  const content = { display_name: 'Synthetic basket maker', description: null, location: 'Synthetic town', approximate_area: null }
  front = await (await sellerApi[front ? 'put' : 'post'](`seller/storefronts${front ? `/${front.id}` : ''}`, { data: { ...content, ...(front ? { expected_revision: front.revision } : {}) } })).json()
  const preview = await (await sellerApi.get(`seller/storefronts/${front.id}/preview`)).json()
  expect((await sellerApi.post(`seller/storefronts/${front.id}/publish`, { data: { expected_revision: preview.revision, preview_hash: preview.preview_hash, approved: true } })).ok()).toBeTruthy()
  const api = await signIn(page, 'buyer')
  await page.goto(`/#/planning/${front.id}`)
  await field(page, 'plan-budget', '20.00')
  await page.getByRole('checkbox', { name: new RegExp(first.product.name) }).check()
  await posted(page, '/buyer/baskets/optimize', () => page.getByRole('button', { name: 'Build a read-only plan' }).click())
  await expect(page.getByRole('heading', { name: /Basket status: ready/ })).toBeVisible()
  await page.getByRole('button', { name: 'Review a separate purchase from this basket' }).click()
  await posted(page, '/orders/preview', () => page.getByRole('button', { name: 'Check current purchase subtotal' }).click())
  await expect(page.getByRole('button', { name: 'Reserve these items & continue' })).toBeVisible()
  await page.locator('select:has(option[value="buyer-bundle"])').selectOption('buyer-bundle')
  for (const item of [first, second]) await page.getByRole('checkbox', { name: new RegExp(item.product.name) }).check()
  await posted(page, '/buyer/bundles/suggest', () => page.getByRole('button', { name: 'Build a read-only plan' }).click())
  await expect(page.getByRole('heading', { name: /pair suggestions/i })).toBeVisible()
  const sellerContext = await browser.newContext({ baseURL: new URL(page.url()).origin })
  const sellerPage = await sellerContext.newPage()
  const session = await signIn(sellerPage)
  await sellerPage.goto(`/#/planning/${front.id}/seller`)
  for (const item of [first, second]) await sellerPage.getByRole('checkbox', { name: new RegExp(item.product.name) }).check()
  await posted(sellerPage, '/seller/bundles/suggest', () => sellerPage.getByRole('button', { name: 'Build a read-only plan' }).click())
  await expect(sellerPage.getByRole('heading', { name: /pair suggestions/i })).toBeVisible()
  await session.dispose(); await sellerContext.close(); await api.dispose(); await sellerApi.dispose()
})

test('individual animal registration and egg production attribution retain source history', async ({ page }) => {
  const api = await signIn(page)
  const today = new Date().toISOString().slice(0, 10)
  const groupResponse = await api.post('seller/livestock/groups', { data: { request_id: crypto.randomUUID(), species: 'chicken', name: `Synthetic attribution flock ${crypto.randomUUID().slice(0, 6)}`, breed: null, notes: null, reported_headcount: 3, headcount_on: today, archived: false, occurred_on: today, reason: 'Synthetic browser attribution fixture' } })
  expect(groupResponse.ok()).toBeTruthy()
  const group = await groupResponse.json()
  await page.goto('/#/livestock/animals')
  for (const [name, value] of Object.entries({ 'livestock-species': 'chicken', 'livestock-identifier': `browser-hen-${crypto.randomUUID().slice(0, 8)}`, 'livestock-name': 'Synthetic browser hen', 'livestock-sex': 'female', 'livestock-occurred': today, 'livestock-reason': 'Synthetic animal registration' })) await field(page, name, value)
  await field(page, 'livestock-group', group.resource_id)
  const animal = await posted(page, '/seller/livestock/animals', () => page.getByRole('button', { name: 'Create private livestock record' }).click())
  await expect(page.getByText(/Synthetic animal registration/).first()).toBeVisible()
  const productResponse = await api.post('products', { data: { name: `Synthetic attributed eggs ${crypto.randomUUID().slice(0, 6)}`, product_type: 'eggs', selling_unit: 'egg' } })
  const product = await productResponse.json()
  await openProduct(page, product.id, 'Completed production')
  for (const [name, value] of Object.entries({ 'production-label': 'Synthetic attributed egg period', 'production-started': today, 'production-completed': today, 'production-total': '6', 'production-sellable': '5' })) await field(page, name, value)
  await field(page, 'livestock-source', group.resource_id)
  await posted(page, '/production-records', () => page.getByRole('button', { name: 'Save completed production report' }).click())
  await page.goto(`/#/livestock/groups/${group.resource_id}`)
  await expect(page.getByRole('heading', { name: 'Synthetic attributed egg period', exact: true })).toBeVisible()
  await expect(page.getByText('Separately registered active animals:', { exact: false })).toBeVisible()
  expect((await api.get(`seller/livestock/animals/${animal.resource_id}`)).ok()).toBeTruthy()
  await api.dispose()
})

test('buyer registration, explicit seller application and logout preserve role boundaries', async ({ page }) => {
  const email = `browser-registration-${crypto.randomUUID().slice(0, 8)}@example.com`
  await page.goto('/#/account')
  await page.getByRole('button', { name: 'Create account', exact: true }).click()
  await field(page, 'email', email)
  await field(page, 'password', process.env.E2E_PASSWORD!)
  await field(page, 'confirmation', process.env.E2E_PASSWORD!)
  await posted(page, '/auth/register', () => page.getByRole('button', { name: 'Create buyer account', exact: true }).click())
  await field(page, 'email', email)
  await field(page, 'password', process.env.E2E_PASSWORD!)
  await posted(page, '/auth/login', () => page.getByRole('button', { name: 'Sign in', exact: true }).last().click())
  await posted(page, '/seller-applications', () => page.getByRole('button', { name: 'Request seller access', exact: true }).click())
  await expect(page.getByText('pending', { exact: true })).toBeVisible()
  await page.goto('/#/seller')
  await expect(page.getByRole('link', { name: 'View seller application' })).toBeVisible()
  await page.goto('/#/account')
  const logout = page.waitForResponse(r => r.url().endsWith('/auth/logout'))
  await page.getByRole('button', { name: 'Sign out', exact: true }).click()
  expect((await logout).status()).toBe(204)
  await expect(page.getByLabel('Email', { exact: true })).toBeVisible()
})
