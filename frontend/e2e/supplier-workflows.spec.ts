import { test, expect } from './fixtures'
import { signIn, field, posted, createProduct, openProduct, chooseHistory } from './helpers'
const today = () => new Date().toISOString().slice(0, 10)

test('dated observations normalize into saved comparisons with source evidence', async ({ page }) => {
  const api = await signIn(page)
  const product = await createProduct(api)
  await openProduct(page, product.id, '3 · Compare (optional)')
  await page.getByText('Add a finished-product price observation', { exact: true }).click()
  for (const [name, value] of Object.entries({ 'observation-label': 'Synthetic comparable loaf', 'observation-price': '5.00', 'observation-quantity': '1', 'observation-unit': 'loaf', 'source-name': 'Synthetic paper quote', 'source-kind': 'document', 'source-reference': 'Browser fixture, not a live retailer price', 'observation-location': 'Synthetic town', 'observation-date': today(), 'quality-notes': 'Quality equivalence not established' })) await field(page, name, value)
  await posted(page, '/price-observations', () => page.getByRole('button', { name: 'Save observation', exact: true }).click())
  const picker = page.getByRole('group', { name: 'Price observations', exact: true })
  await picker.getByRole('checkbox').first().check()
  await field(page, 'comparison-quantity', '1')
  await field(page, 'comparison-unit', 'loaf')
  await field(page, 'comparison-age', '30')
  const report = await posted(page, '/price-comparisons', () => page.getByRole('button', { name: 'Compare & save report' }).click())
  await expect(page.getByRole('heading', { name: 'Selected price context' })).toBeVisible()
  await page.getByRole('button', { name: /Quality Lock/ }).first().click()
  await page.getByRole('button', { name: '3 · Compare (optional)', exact: true }).click()
  await chooseHistory(page, 'Comparison reports', report.id)
  await expect(page.getByText('Browser fixture, not a live retailer price', { exact: false }).first()).toBeVisible()
  await api.dispose()
})

test('supplier quotes with failed mandatory rules stay excluded in saved reports', async ({ page }) => {
  const api = await signIn(page)
  const product = await createProduct(api)
  await openProduct(page, product.id, 'Supplier savings')
  await field(page, 'sourcing-label', 'Synthetic bread flour')
  const input = await posted(page, '/sourcing-inputs', () => page.getByRole('button', { name: 'Create private sourcing input' }).click())
  await page.getByText('Add a yes/no input requirement', { exact: false }).click()
  await field(page, 'supply-rule-label', 'Synthetic organic requirement')
  await field(page, 'supply-rule-key', 'organic')
  await posted(page, '/quality-locks', () => page.getByRole('button', { name: 'Save input requirement' }).click())
  await page.getByText('Add a sourced supplier quote', { exact: true }).click()
  for (const [name, value] of Object.entries({ 'supplier-name': 'Synthetic supplier', 'supplier-location': 'Synthetic town', 'package-price': '1.00', 'package-quantity': '1', 'package-unit': 'kg', 'usable-fraction': '1', 'minimum-packages': '1', 'transport-cost': '0', 'supplier-availability': 'available', 'supplier-source-name': 'Synthetic documented quote', 'supplier-source-kind': 'document', 'supplier-reference': 'Browser fixture only', 'supplier-date': today(), 'supply-claim-organic': 'false' })) await field(page, name, value)
  await posted(page, '/supplier-quotes', () => page.getByRole('button', { name: 'Save private quote', exact: true }).click())
  const picker = page.getByRole('group', { name: 'Supplier quotes', exact: true })
  await picker.getByRole('checkbox').first().check()
  await field(page, 'required-supply-quantity', '1')
  await field(page, 'required-supply-unit', 'kg')
  await field(page, 'supplier-max-age', '30')
  const report = await posted(page, '/supplier-comparisons', () => page.getByRole('button', { name: 'Compare & save supplier report' }).click())
  const saved = await (await api.get(`products/${product.id}/sourcing-inputs/${input.id}/supplier-comparisons/${report.id}`)).json()
  expect(JSON.stringify(saved)).toMatch(/quality|mandatory|failed/i)
  await expect(page.getByText(/excluded|failed/i).last()).toBeVisible()
  await posted(page, '/supplier-recommendations', () => page.getByRole('button', { name: 'Review eligible options' }).click())
  await expect(page.getByRole('heading', { name: 'Options for input review' })).toBeVisible()
  await api.dispose()
})

test('private supplier profile, experience and reliability are revisitable', async ({ page }) => {
  const profileName = `Edited synthetic supplier profile ${crypto.randomUUID().slice(0, 8)}`
  const api = await signIn(page)
  await page.goto('/#/suppliers')
  await field(page, 'supplier-profile-name', 'Synthetic browser supplier profile')
  await field(page, 'supplier-profile-location', 'Synthetic town')
  const created = await posted(page, '/seller/suppliers', () => page.getByRole('button', { name: 'Create private supplier profile', exact: true }).click())
  await expect(page.getByRole('heading', { name: 'Record what you observed.' })).toBeVisible()
  await field(page, 'experience-label', 'Synthetic punctual delivery')
  await field(page, 'experience-observed', today())
  await field(page, 'experience-rating', '4')
  await field(page, 'experience-promised', today())
  await field(page, 'experience-received', today())
  await posted(page, '/experiences', () => page.getByRole('button', { name: 'Save reported observation' }).click())
  await expect(page.getByText(/1 current observation/)).toBeVisible()
  await page.getByText('Edit private profile or archive it', { exact: true }).click()
  await field(page, 'supplier-profile-name', profileName)
  await field(page, 'supplier-edit-reason', 'Synthetic profile correction')
  await posted(page, `/suppliers/${created.supplier_id}`, () => page.getByRole('button', { name: 'Save private profile change' }).click())
  await page.goto('/#/seller')
  await page.goto(`/#/suppliers/${created.supplier_id}`)
  await expect(page.getByRole('heading', { name: profileName, exact: true })).toBeVisible()
  await expect(page.getByText(/1 current observation/)).toBeVisible()
  await api.dispose()
})
