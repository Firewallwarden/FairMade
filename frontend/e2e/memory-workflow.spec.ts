import { test, expect } from './fixtures'
import { signIn, apiForRole, seedListing, field, posted } from './helpers'

test('real model memory proposal requires existing consent and a separately reviewed save', async ({ page }) => {
  test.skip(process.env.E2E_PROVIDERS !== '1', 'Requires the real local model explicitly enabled.')
  test.setTimeout(360_000)
  const api = await signIn(page, 'buyer')
  await page.goto('/#/preferences')
  await field(page, 'preference-budget', '20')
  await page.locator('[name="confirm-preferences"]').check()
  await posted(page, '/personalization', () => page.getByRole('button', { name: 'Save reviewed preferences' }).click())
  const before = await (await api.get('buyer/personalization')).json()
  const seller = await apiForRole('seller')
  const { listing } = await seedListing(seller)
  await page.goto(`/#/assistant/buyer/${listing.id}`)
  await posted(page, '/assistants/conversations', () => page.getByRole('button', { name: 'Start saved conversation' }).click())
  await field(page, 'assistant-question', 'I prefer sourdough bread and my per-item budget is USD 8. Explain the recorded evidence and unknowns for this bread.')
  await posted(page, '/turns', () => page.getByRole('button', { name: 'Ask FairMade', exact: true }).last().click())
  await page.getByText('Review preferences from this question', { exact: true }).click()
  await posted(page, '/remember', () => page.getByRole('button', { name: 'Propose preferences from my question' }).click())
  const proposed = await (await api.get('buyer/personalization')).json()
  expect(proposed.revision).toBe(before.revision)
  expect(proposed.preferences).toEqual(before.preferences)
  await field(page, 'preference-budget', '8')
  await page.locator('[name="preference-type"][value="sourdough"]').check()
  await expect(page.getByRole('button', { name: 'Save reviewed preferences' })).toBeDisabled()
  await page.locator('[name="confirm-preferences"]').check()
  await posted(page, '/personalization', () => page.getByRole('button', { name: 'Save reviewed preferences' }).click())
  await expect(page).toHaveURL(/#\/preferences$/)
  const saved = await (await api.get('buyer/personalization')).json()
  expect(saved.preferences.budget_per_item).toMatch(/^8(?:\.0+)?$/)
  expect(saved.preferences.product_types).toContain('sourdough')
  await api.dispose(); await seller.dispose()
})
