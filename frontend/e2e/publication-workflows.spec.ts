import { test, expect } from './fixtures'
import { signIn, field, posted, createProduct, seedAnalysis, seedListing, chooseHistory, openProduct } from './helpers'

test('seller edits a saved Passport, handles a revision conflict, approves fresh previews, publishes and withdraws', async ({ page }) => {
  const api = await signIn(page)
  const product = await createProduct(api)
  const analysis = await seedAnalysis(api, product.id)
  await openProduct(page, product.id, '4 · Review & publish')
  await field(page, 'stock-count', '20')
  await posted(page, '/inventory', () => page.getByRole('button', { name: 'Save stock', exact: true }).click())
  await chooseHistory(page, 'Saved analysis', analysis.id)
  await field(page, 'passport-title', 'Synthetic public bread')
  await field(page, 'passport-price', '4.00')
  await page.locator('[name="include_unit_cost"]').check()
  const draft = await posted(page, '/passports', () => page.getByRole('button', { name: 'Build private review & preview' }).click())
  await page.getByText('Recover a previous Passport draft or publication', { exact: true }).click()
  const picker = page.getByRole('group', { name: 'Passport drafts', exact: true })
  await picker.getByRole('button', { name: 'Refresh passport drafts' }).click()
  await picker.locator('select').selectOption('')
  await chooseHistory(page, 'Passport drafts', draft.id)
  const editor = page.locator('section').filter({ has: page.getByRole('heading', { name: 'Edit saved Passport draft', exact: true }) }).last()
  await expect(editor.locator('[name="include_unit_cost"]')).toBeChecked()
  await editor.locator('[name="edit-title"]').fill('Edited synthetic public bread')
  await expect(page.getByRole('button', { name: 'Publish approved Passport' })).toHaveCount(0)
  const current = await (await api.get(`products/${product.id}/passports/${draft.id}`)).json()
  await api.put(`products/${product.id}/passports/${draft.id}`, { data: { ...current.content, title: 'Concurrent synthetic edit', expected_revision: current.revision } })
  await editor.getByRole('button', { name: 'Save Passport changes' }).click()
  await expect(page.getByRole('alert').filter({ hasText: /reload|revision|changed|stale/i })).toBeVisible()
  await editor.getByRole('button', { name: 'Reload saved draft after a conflict' }).click()
  await expect(editor.locator('[name="edit-title"]')).toHaveValue('Concurrent synthetic edit')
  await editor.locator('[name="edit-title"]').fill('Edited synthetic public bread')
  await posted(page, `/passports/${draft.id}`, () => editor.getByRole('button', { name: 'Save Passport changes' }).click())
  await page.getByRole('button', { name: 'Generate fresh Passport preview' }).click()
  await page.locator('[name="approve-passport"]').check()
  await posted(page, '/publish', () => page.getByRole('button', { name: 'Publish approved Passport' }).click())
  for (const [name, value] of Object.entries({ 'listing-seller': 'Synthetic browser maker', 'listing-location': 'Synthetic town', 'listing-summary': 'Synthetic browser listing', 'listing-quantity': '1', 'listing-quantity-unit': 'loaf' })) await field(page, name, value)
  await posted(page, '/listing', () => page.getByRole('button', { name: 'Save & preview listing' }).click())
  await page.locator('[name="approve-listing"]').check()
  await posted(page, '/activate', () => page.getByRole('button', { name: 'Publish approved listing' }).click())
  await expect(page.getByRole('link', { name: 'View public listing' })).toBeVisible()
  await page.getByRole('button', { name: 'Refresh publication history' }).click()
  page.once('dialog', dialog => dialog.accept())
  await posted(page, '/withdraw', async () => page.getByRole('button', { name: 'Withdraw published Passport' }).click())
  await expect(page.getByText(/Passport withdrawn. Linked listings/)).toBeVisible()
  await expect(page.getByRole('link', { name: 'View public listing' })).toHaveCount(0)
  await api.dispose()
})

test('saved pricing reviews expose recorded economics, explanations and private sources', async ({ page }) => {
  const api = await signIn(page)
  const product = await createProduct(api)
  const analysis = await seedAnalysis(api, product.id)
  const response = await api.post(`products/${product.id}/pricing-reviews`, { data: { pricing_analysis_id: analysis.id } })
  expect(response.ok()).toBeTruthy()
  const review = await response.json()
  await openProduct(page, product.id, 'Business reports')
  await page.getByRole('button', { name: new RegExp(review.id) }).click()
  await expect(page.getByRole('heading', { name: 'Recorded explanations' })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Recorded warnings' })).toBeVisible()
  await page.getByText('Complete recorded source evidence', { exact: true }).click()
  await expect(page.locator('pre')).toContainText('pricing_analysis')
  await api.dispose()
})

test('a replacement Passport does not advertise an older hidden listing as public', async ({ page }) => {
  const api = await signIn(page)
  const { product, listing, draft } = await seedListing(api)
  await openProduct(page, product.id, '4 · Review & publish')
  await page.getByText('Recover a previous Passport draft or publication', { exact: true }).click()
  await chooseHistory(page, 'Passport drafts', draft.id)
  const editor = page.locator('section').filter({ has: page.getByRole('heading', { name: 'Edit saved Passport draft', exact: true }) }).last()
  await expect(editor).toBeVisible()
  page.once('dialog', dialog => dialog.accept())
  await posted(page, '/withdraw', () => page.getByRole('button', { name: 'Withdraw published Passport' }).click())
  await editor.locator('[name="edit-title"]').fill('Replacement synthetic Passport')
  await posted(page, `/passports/${draft.id}`, () => editor.getByRole('button', { name: 'Save Passport changes' }).click())
  await page.getByRole('button', { name: 'Generate fresh Passport preview' }).click()
  await page.locator('[name="approve-passport"]').check()
  await posted(page, '/publish', () => page.getByRole('button', { name: 'Publish approved Passport' }).click())
  expect((await api.get(`marketplace/listings/${listing.id}`)).status()).toBe(404)
  await expect(page.getByRole('link', { name: 'View public listing', exact: true })).toHaveCount(0)
  await api.dispose()
})

test('itemized sales can change UTC period, page empty results, and retry without invented amounts', async ({ page }) => {
  const api = await signIn(page)
  await page.goto('/#/seller')
  await page.getByRole('button', { name: 'Itemized sales report', exact: true }).click()
  await field(page, 'sales-start', '2026-01-01')
  await field(page, 'sales-end', '2026-02-01')
  const response = page.waitForResponse(r => r.url().includes('/seller/sales/orders?') && r.url().includes('2026-01-01'))
  await page.getByRole('button', { name: 'Load itemized sales' }).click()
  expect((await response).ok()).toBeTruthy()
  await expect(page.getByText('No verified sales on this page for the selected period.')).toBeVisible()
  await expect(page.getByRole('button', { name: 'Next sales' })).toBeDisabled()
  await page.getByRole('button', { name: 'Refresh sales report' }).click()
  await expect(page.getByText('No verified sales on this page for the selected period.')).toBeVisible()
  await api.dispose()
})
